"use client";

import { zodResolver } from "@hookform/resolvers/zod";
import { useEffect } from "react";
import { useForm } from "react-hook-form";
import { toast } from "sonner";
import { z } from "zod";

import { Button } from "@/components/ui/button";
import { DatePicker } from "@/components/ui/date-picker";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from "@/components/ui/form";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";

import type { TransactionListItem } from "../actions/transactions-actions";
import { useUpdateTransaction } from "../hooks/use-transactions";
import { defaultAccrualMonth, TRANSACTION_KIND_LABEL } from "../schema";

const FormSchema = z.object({
  amount: z.string().regex(/^\d+(\.\d+)?$/, "Monto requerido."),
  transaction_date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Fecha inválida."),
  accrual_month: z
    .string()
    .regex(/^\d{4}-\d{2}-\d{2}$/, "Mes devengado inválido."),
  description: z.string().trim().max(500),
});

type FormValues = z.infer<typeof FormSchema>;

function toValues(tx: TransactionListItem): FormValues {
  return {
    amount: String(tx.amount),
    transaction_date: tx.transaction_date,
    accrual_month: tx.accrual_month,
    description: tx.description ?? "",
  };
}

/**
 * Edits a manual movement: amount, dates and description. Account, channel
 * and kind stay (a different account or kind is a different movement). The
 * database refuses movements generated by a document or in a closed period;
 * that refusal is shown as is.
 */
export function EditTransactionDialog({
  transaction,
  onOpenChange,
}: {
  transaction: TransactionListItem | null;
  onOpenChange: (open: boolean) => void;
}) {
  const updateMut = useUpdateTransaction();
  const form = useForm<FormValues>({
    resolver: zodResolver(FormSchema),
    defaultValues: transaction ? toValues(transaction) : undefined,
  });

  useEffect(() => {
    if (transaction) form.reset(toValues(transaction));
  }, [transaction, form]);

  function onSubmit(values: FormValues) {
    if (!transaction) return;
    updateMut.mutate(
      {
        id: transaction.id,
        amount: values.amount,
        transaction_date: values.transaction_date,
        accrual_month: values.accrual_month,
        description: values.description,
        counterparty_client_id: transaction.counterparty_client_id,
      },
      {
        onSuccess: () => {
          toast.success("Movimiento actualizado.");
          onOpenChange(false);
        },
        onError: (err) => toast.error(err.message),
      },
    );
  }

  return (
    <Dialog open={transaction !== null} onOpenChange={onOpenChange}>
      <DialogContent className="max-h-[90vh] overflow-y-auto sm:max-w-lg">
        <DialogHeader>
          <DialogTitle>Editar movimiento</DialogTitle>
          <DialogDescription>
            {transaction
              ? `${TRANSACTION_KIND_LABEL[transaction.kind]} · ${transaction.account_name} · ${transaction.channel_name}`
              : null}
          </DialogDescription>
        </DialogHeader>
        <Form {...form}>
          <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-4">
            <FormField
              control={form.control}
              name="amount"
              render={({ field }) => (
                <FormItem>
                  <FormLabel className="text-xs">
                    Monto ({transaction?.currency})
                  </FormLabel>
                  <FormControl>
                    <Input inputMode="decimal" {...field} />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />
            <div className="grid gap-3 sm:grid-cols-2">
              <FormField
                control={form.control}
                name="transaction_date"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel className="text-xs">Fecha</FormLabel>
                    <FormControl>
                      <DatePicker
                        value={field.value}
                        onChange={(v) => {
                          field.onChange(v);
                          form.setValue(
                            "accrual_month",
                            defaultAccrualMonth(v),
                            { shouldDirty: true },
                          );
                        }}
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <FormField
                control={form.control}
                name="accrual_month"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel className="text-xs">
                      Mes devengado{" "}
                      <span className="text-muted-foreground">(día 1)</span>
                    </FormLabel>
                    <FormControl>
                      <Input
                        type="month"
                        value={field.value?.slice(0, 7) ?? ""}
                        onChange={(e) => field.onChange(`${e.target.value}-01`)}
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
            </div>
            <FormField
              control={form.control}
              name="description"
              render={({ field }) => (
                <FormItem>
                  <FormLabel className="text-xs">Descripción</FormLabel>
                  <FormControl>
                    <Textarea rows={2} {...field} />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />
            <div className="flex justify-end gap-2">
              <Button
                type="button"
                variant="ghost"
                onClick={() => onOpenChange(false)}
                disabled={updateMut.isPending}
              >
                Cancelar
              </Button>
              <Button
                type="submit"
                disabled={updateMut.isPending || !form.formState.isDirty}
              >
                {updateMut.isPending ? "Guardando…" : "Guardar"}
              </Button>
            </div>
          </form>
        </Form>
      </DialogContent>
    </Dialog>
  );
}
