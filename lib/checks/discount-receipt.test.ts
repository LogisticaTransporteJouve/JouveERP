describe("parseDiscountReceipt", () => {
  it("reads Galicia's receipt: the operation, its cheques and its costs", () => {
    const r = parseDiscountReceipt(GALICIA);
    if (!r.ok) throw new Error(r.error);
    expect(r.receipt).toMatchObject({
      operation: "0002420838",
      date: "2026-11-03",
      gross: 13577855.9,
      interest: 157316.82,
      iva: 16518.27,
      iva_perception: 2346.47,
      stamp_tax: 6816.37,
      iibb: 2502.9,
      net: 13392355.07,
    });
    expect(
      r.receipt.cheques.map((c) => [c.loan_number, c.check_number, c.amount]),
    ).toEqual([
      ["808150912647", "1796", 134384],
      ["808150912652", "2059", 165878.39],
      ["808150912652", "5473", 7056795.16],
      ["808150912668", "10114175", 1528950.25],
      ["808150912673", "10024214", 3547538.5],
      ["808150912689", "41072338", 1144309.6],
    ]);
    expect(r.receipt.cheques[0]).toMatchObject({
      drawer_cuit: "30666236471",
      due_date: "2026-11-07",
    });
  });

  it("knows Galicia as the buyer from the receipt's terms", () => {
    const r = parseDiscountReceipt(
      `${GALICIA}\nque el Banco de Galicia y Buenos Aires S.A. adquiera`,
    );
    expect(r.ok && r.receipt.buyer).toEqual({
      name: "Banco Galicia",
      cuit: "30500001735",
    });
  });

  it("says when the text is not a discount receipt", () => {
    expect(parseDiscountReceipt("Comprobante de transferencia").ok).toBe(false);
  });
});
